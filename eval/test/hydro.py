"""Hydrodynamic ground truth for the glider-design benchmark (held-out slice).

Pure standard-library Python so the evaluator has no numerical dependencies.

The paper labels cage-parameterised hulls with OpenFOAM, which is not
available here. Each *fluid instance* is a deterministic CFD stand-in that
maps a hull descriptor (8 normalised cage features) and an angle of attack to
drag and lift coefficients. An instance combines

* a lifting-surface / drag-build-up model whose coefficients vary per instance
  (aspect-ratio lift slope, stall and separation onset, skin friction, an
  internal-hardware fairing penalty for hulls too thin to house the payload
  tube), and
* instance-specific interference effects: smooth multiplicative lift and drag
  corrections centred on mixed hull geometries, each active over a band of
  angles of attack.

``coefficients`` is the true response used for scoring. The published labelled
dataset is a simulation of it: every label carries an independent,
deterministic multiplicative error (log-normal, ``LABEL_NOISE``), standing in
for CFD discretisation/convergence error (the paper reports 4.5% between
simulated and wind-tunnel lift-to-drag).

This copy serves the held-out instances; their seeds exist only in
``eval/test/evaluate.py``. The development instances are generated by an
independent public copy under ``eval/train``.
"""

