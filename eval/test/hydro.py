NB = len(BASE_SHAPES)
ND = len(BASE_SHAPES[0])
TORPEDO_INDEX = 0
FRANGE = [max(b[j] for b in BASE_SHAPES) - min(b[j] for b in BASE_SHAPES) for j in range(ND)]

LABEL_AOA_DEG = (-30.0, -15.0, 0.0, 15.0, 30.0)
MORPHS_PER_PAIR = 10
AOA_RANGE_DEG = (-30.0, 30.0)
LABEL_NOISE = 0.05
N_QUERIES = 400
QUERY_AOA_RANGE_DEG = (3.0, 30.0)

GENERATOR = {
    "eps_phys": 0.15,
    "t_req": (0.24, 0.32),
    "k_fair": (0.6, 1.2),
    "n_features": 10,
    "face_size": (3, 5),
    "width": (0.15, 0.30),
    "amp_favourable": (0.3, 0.8),
    "amp_adverse": (0.1, 0.4),
    "p_favourable": 0.7,
    "aoa_centre": (-5.0, 35.0),
    "aoa_width": (8.0, 18.0),
}


def _uniform(rng: random.Random, lo: float, hi: float) -> float:
    return lo + (hi - lo) * rng.random()


def _int_between(rng: random.Random, lo: int, hi: int) -> int:
    return lo + min(int(rng.random() * (hi - lo + 1)), hi - lo)


def _subset(rng: random.Random, n: int, k: int) -> list[int]:
    idx = list(range(n))
    for i in range(n - 1, 0, -1):
        j = min(int(rng.random() * (i + 1)), i)
        idx[i], idx[j] = idx[j], idx[i]
    return idx[:k]


def mix(weights: list[float]) -> list[float]:
    return [sum(weights[i] * BASE_SHAPES[i][j] for i in range(NB)) for j in range(ND)]


def make_instance(seed: str, generator: dict | None = None) -> dict:
    g = dict(GENERATOR)
    if generator:
        g.update(generator)
    rng = random.Random("glider-fluid::" + str(seed))
    e = g["eps_phys"]

    def vary(v: float) -> float:
        return v * _uniform(rng, 1.0 - e, 1.0 + e)

    phys = {
        "k_aspect": vary(5.5), "k_thick": vary(0.10), "k_blunt": vary(0.08),
        "stall0": vary(18.0), "stall_sweep": vary(12.0), "sep0": vary(14.0),
        "sep_sweep": vary(10.0), "oswald": vary(0.70), "camber_shift": vary(7.0),
        "t_req": _uniform(rng, *g["t_req"]), "k_fair": _uniform(rng, *g["k_fair"]),
    }
    features = []
    for _ in range(g["n_features"]):
        k = _int_between(rng, g["face_size"][0], g["face_size"][1])
        members = _subset(rng, NB, k)
        raw = [_uniform(rng, 0.6, 1.4) for _ in members]
        tot = sum(raw)
        w = [0.0] * NB
        for m, v in zip(members, raw):
            w[m] = v / tot
        centre = mix(w)
        r = _uniform(rng, *g["width"])
        inv_s2 = []
        for j in range(ND):
            s = r * FRANGE[j] * _uniform(rng, 0.75, 1.25)
            inv_s2.append(1.0 / (s * s))
        mu = _uniform(rng, *g["aoa_centre"])
        tau = _uniform(rng, *g["aoa_width"])
        favourable = rng.random() < g["p_favourable"]
        total = _uniform(rng, *(g["amp_favourable"] if favourable else g["amp_adverse"]))
        split = _uniform(rng, 0.3, 0.7)
        sign = 1.0 if favourable else -1.0
        features.append({
            "centre": centre, "inv_s2": inv_s2, "mu": mu, "inv_t2": 1.0 / (tau * tau),
            "lift": sign * total * split, "drag": -sign * total * (1.0 - split),
        })
    return {"phys": phys, "features": features}


def coefficients(instance: dict, shape: list[float], aoa_deg: float) -> tuple[float, float]:
    """Return (c_d, c_l) for a hull descriptor at an angle of attack in degrees."""

    p = instance["phys"]
    span, sweep, camber, thick, tail, blunt, fin, sym = (float(v) for v in shape)
    aoa = float(aoa_deg)
    aspect = 1.0 + p["k_aspect"] * span / (0.55 + thick)
    surface = min(max(0.08 + 1.05 * span + 0.25 * tail + 0.12 * fin, 0.08), 1.25)
    slope = (1.6 + 0.42 * aspect + 1.25 * tail + 0.55 * fin) * (0.82 + 0.18 * sym) * surface
    zero_lift = math.radians(-p["camber_shift"] * camber + 1.5 * (blunt - 0.15))
    eff = math.radians(aoa) - zero_lift
    eff_deg = abs(math.degrees(eff))
    z = (eff_deg - (p["stall0"] + p["stall_sweep"] * sweep)) / 3.2
    stall = 1.0 / (1.0 + math.exp(min(z, 60.0)))
    cl = slope * math.sin(eff) * math.cos(eff) * (0.45 + 0.55 * stall)
    cl += surface * (0.20 * camber + 0.06 * fin) - 0.04 * (1.0 - sym)
    wetted = 0.045 + p["k_thick"] * thick + p["k_blunt"] * blunt + 0.025 * fin
    fairing = p["k_fair"] * max(p["t_req"] - thick, 0.0) ** 2
    induced = cl * cl / (math.pi * max(aspect, 0.5) * (p["oswald"] + 0.22 * sym))
    separation = 0.018 * max(eff_deg - (p["sep0"] + p["sep_sweep"] * sweep), 0.0) ** 1.35 / 10.0
    cd = wetted + fairing + induced + separation + 0.018 * (1.0 - sym)
    cd += 0.010 * max(span - 0.86, 0.0) ** 2
    g_lift = 0.0
    g_drag = 0.0
    x = (span, sweep, camber, thick, tail, blunt, fin, sym)
    for f in instance["features"]:
        c = f["centre"]
        s = f["inv_s2"]
        q = 0.0
        for j in range(ND):
            d = x[j] - c[j]
            q += d * d * s[j]
        da = aoa - f["mu"]
        k = math.exp(-0.5 * (q + da * da * f["inv_t2"]))
        g_lift += f["lift"] * k
        g_drag += f["drag"] * k
    cl *= math.exp(g_lift)
    cd *= math.exp(g_drag)
    return max(cd, 1e-4), max(cl, 0.0)


def lift_to_drag(instance: dict, shape: list[float], aoa_deg: float) -> float:
    cd, cl = coefficients(instance, shape, aoa_deg)
    return cl / cd


def dataset_shapes(morphs_per_pair: int = MORPHS_PER_PAIR) -> list[list[float]]:
    """Base shapes followed by pairwise morphs, in the public label-table order."""

    rows = [list(b) for b in BASE_SHAPES]
    for i in range(NB):
        for j in range(i + 1, NB):
            for k in range(1, morphs_per_pair + 1):
                t = k / (morphs_per_pair + 1)
                rows.append([(1.0 - t) * BASE_SHAPES[i][d] + t * BASE_SHAPES[j][d] for d in range(ND)])
    return rows


def simulated_labels(seed: str, instance: dict) -> list[tuple[int, float, float, float]]:
    """Published labelled dataset: (shape_id, aoa, c_d, c_l) with simulation error."""

    rng = random.Random("glider-labels::" + str(seed))
    rows = []
    for sid, shape in enumerate(dataset_shapes()):
        for aoa in LABEL_AOA_DEG:
            cd, cl = coefficients(instance, shape, aoa)
            cd *= math.exp(LABEL_NOISE * rng.gauss(0.0, 1.0))
            cl *= math.exp(LABEL_NOISE * rng.gauss(0.0, 1.0))
            rows.append((sid, aoa, cd, cl))
    return rows


def query_inputs(instance_id: str, n: int = N_QUERIES) -> list[dict]:
    """Held-out hull/angle pairs on which predicted coefficients are scored."""

    rng = random.Random("glider-queries::" + str(instance_id))
    out = []
    for i in range(n):
        if i % 2 == 0:
            raw = [-math.log(1.0 - rng.random()) for _ in range(NB)]
        else:
            k = _int_between(rng, 3, 5)
            raw = [0.0] * NB
            for m in _subset(rng, NB, k):
                raw[m] = _uniform(rng, 0.6, 1.4)
        tot = sum(raw)
        w = [round(v / tot, 6) for v in raw]
        w[max(range(NB), key=lambda m: w[m])] += round(1.0 - sum(w), 6)
        aoa = round(_uniform(rng, *QUERY_AOA_RANGE_DEG), 3)
        out.append({"weights": w, "shape": mix(w), "aoa_deg": aoa})
    return out
